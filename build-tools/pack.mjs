// Seals the dashboard for the app: every file in <webdir> goes into one AES-256-GCM archive (app.pak); the app gets
// the archive's SHA-256 and the key in BuildInfo.swift, and refuses an archive that does not match.
//   node build-tools/pack.mjs <webdir> <out/app.pak> <out/BuildInfo.swift> <version>
// The version (from the shared VERSION file) is compiled in too: the engine reports it in health and bootstrap.
import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import {join, relative, extname} from 'node:path';
import {randomBytes, createCipheriv, createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {updateConfig} from '../update/build-config.mjs';

const [webdir, outPak, outSwift, version] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version || '')) throw new Error('pack.mjs needs the version (x.y.z) as its fourth argument');
const TYPES = {'.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.ttf': 'font/ttf', '.txt': 'text/plain; charset=utf-8'};
const files = [];
const walk = d => { for (const n of readdirSync(d).sort()) { const p = join(d, n); if (n.startsWith('.')) continue; if (statSync(p).isDirectory()) walk(p); else files.push(p) } };
walk(webdir);
const index = {}, parts = []; let offset = 0;
for (const f of files) {
  const data = readFileSync(f), type = TYPES[extname(f)];
  if (!type) throw new Error('unknown file type in the dashboard: ' + f);
  index[relative(webdir, f)] = [offset, data.length, type]; parts.push(data); offset += data.length;
}
const indexBuf = Buffer.from(JSON.stringify(index)), head = Buffer.alloc(4); head.writeUInt32BE(indexBuf.length);
const plain = Buffer.concat([head, indexBuf, ...parts]);
const key = randomBytes(32), iv = randomBytes(12), cipher = createCipheriv('aes-256-gcm', key, iv);
const sealed = Buffer.concat([iv, cipher.update(plain), cipher.final(), cipher.getAuthTag()]);
writeFileSync(outPak, sealed);
const sha = createHash('sha256').update(sealed).digest('hex');
// The key is stored as two halves that only make sense together (keeps it out of plain `strings` output).
const mask = randomBytes(32), masked = Buffer.from(key.map((b, i) => b ^ mask[i]));
const pub = execFileSync(process.execPath, [join(import.meta.dirname, '../license/issue.mjs'), '--public-key']).toString().trim();
const arr = b => '[' + [...b].map(x => '0x' + x.toString(16).padStart(2, '0')).join(', ') + ']';
// The update check: the feed address and the trusted update keys (update/config.json; empty means not set up).
const upd = updateConfig({licenceKey: pub});
writeFileSync(outSwift, `// Generated by build-tools/pack.mjs: do not edit.
import Foundation
enum BuildInfo {
  // One literal holds the version, so the release check can read it from the binary (short Swift strings are not
  // stored as text); version is its last word.
  static let stamp = "187N Agent HQ student edition ${version}"
  static var version: String { String(stamp.split(separator: " ").last ?? "") }
  static let pakSHA256 = "${sha}"
  static func pakKey() -> [UInt8] { let a: [UInt8] = ${arr(masked)}; let b: [UInt8] = ${arr(mask)}; return zip(a, b).map { $0 ^ $1 } }
  static let licensePublicKey = Data(base64Encoded: "${pub}")!
  static let updateFeedURL = ${JSON.stringify(upd.feedURL)}
  static let updateKeys: [String] = [${upd.keys.map(k => JSON.stringify(k)).join(', ')}]
}
`);
console.log('sealed ' + files.length + ' files · ' + (sealed.length / 1e6).toFixed(1) + ' MB · updates ' + (upd.configured ? 'from ' + upd.feedURL + ' (' + upd.keys.length + ' key' + (upd.keys.length > 1 ? 's' : '') + ')' : 'not set up (update/config.json)'));
